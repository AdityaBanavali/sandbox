"""Computer vision registration and surface difference analysis for CivicFix AI.

Performs ORB feature detection, RANSAC homography alignment, structural change
magnitude evaluation, Otsu defect ROI localization, and surface roughness drop
analysis via Laplacian variance.
"""

from __future__ import annotations

import base64
import logging
from dataclasses import dataclass
from typing import Optional

import cv2
import numpy as np

from app.schemas import VisionResult
from app.services.errors import InvalidImageError

logger = logging.getLogger(__name__)


@dataclass
class VisionArtifacts:
    """Intermediate and final visual artifacts generated by the vision pipeline."""

    aligned_after: Optional[np.ndarray]
    diff_heatmap: Optional[np.ndarray]
    defect_roi: Optional[tuple[int, int, int, int]]


def encode_jpeg_b64(img: Optional[np.ndarray], quality: int = 85) -> str:
    """Encodes an OpenCV image array as a base64-encoded JPEG string.

    Args:
        img: OpenCV image ndarray (BGR or grayscale).
        quality: JPEG compression quality (0-100).

    Returns:
        Base64 string representing the compressed JPEG image, or empty string on failure.
    """
    if img is None or img.size == 0:
        return ""
    try:
        success, buffer = cv2.imencode(
            ".jpg", img, [int(cv2.IMWRITE_JPEG_QUALITY), quality]
        )
        if not success:
            logger.warning("cv2.imencode returned False.")
            return ""
        return base64.b64encode(buffer).decode("utf-8")
    except Exception as exc:
        logger.warning("Failed to encode image to base64 JPEG: %s", exc)
        return ""


def _downscale(img: np.ndarray, max_side: int = 1280) -> np.ndarray:
    """Downscales an image preserving aspect ratio so the longest side <= max_side."""
    h, w = img.shape[:2]
    if max(h, w) <= max_side:
        return img
    scale = max_side / float(max(h, w))
    new_w = max(1, int(round(w * scale)))
    new_h = max(1, int(round(h * scale)))
    return cv2.resize(img, (new_w, new_h), interpolation=cv2.INTER_AREA)


def _decode_image(image_bytes: bytes, label: str) -> np.ndarray:
    """Decodes image bytes into an OpenCV BGR ndarray, raising InvalidImageError on failure."""
    if not image_bytes:
        raise InvalidImageError(f"{label.capitalize()} image buffer is empty.")

    try:
        np_arr = np.frombuffer(image_bytes, np.uint8)
        img = cv2.imdecode(np_arr, cv2.IMREAD_COLOR)
        if img is None or img.size == 0:
            raise InvalidImageError(f"Failed to decode {label} image.")
        return _downscale(img, max_side=1280)
    except InvalidImageError:
        raise
    except Exception as exc:
        logger.error("Exception decoding %s image: %s", label, exc)
        raise InvalidImageError(f"Corrupted or invalid {label} image: {exc}") from exc


def _is_homography_valid(H: Optional[np.ndarray], inliers: int) -> bool:
    """Validates the homography matrix to prevent degenerate or inverted warps."""
    if H is None or inliers < 8:
        return False
    if np.any(np.isnan(H)) or np.any(np.isinf(H)):
        return False
    try:
        det = float(np.linalg.det(H[:2, :2]))
        if det <= 0.05 or det >= 20.0:
            logger.warning("Degenerate homography determinant: %s", det)
            return False
        # Guard against extreme perspective distortions
        if abs(H[2, 0]) > 0.02 or abs(H[2, 1]) > 0.02:
            logger.warning("Extreme perspective components in homography: %s, %s", H[2, 0], H[2, 1])
            return False
        return True
    except Exception as exc:
        logger.warning("Homography validation check failed: %s", exc)
        return False


def _compute_vision_score(
    alignment_succeeded: bool,
    inliers: int,
    change_magnitude: float,
    roughness_drop_ratio: Optional[float],
) -> float:
    """Calculates deterministic Vision Trust Score (0-100).

    Scoring composition:
    1. Alignment (0-35 points):
       - If alignment succeeded: 35.0 * min(inliers / 30.0, 1.0)
       - If alignment failed: 0.0 points
    2. Change Magnitude (0-30 points) with bell-shaped reward:
       - 0.05 to 0.35: 30.0 points (optimal repair delta)
       - < 0.05: linear ramp from 0.0 to 30.0 (penalty for static/unchanged scenes)
       - 0.35 to 0.60: linear descent from 30.0 to 0.0
       - > 0.60: minimal reward <= 5.0 decaying to 0.0 (penalty for completely different scenes)
    3. Surface Roughness Drop (0-35 points):
       - 35.0 * clamp(roughness_drop_ratio / 0.5, 0.0, 1.0)
       - 0.0 points if drop is negative (rougher) or missing
    Final score is clamped to [0.0, 100.0].
    """
    # 1. Alignment score (0-35)
    if alignment_succeeded:
        score_align = 35.0 * min(float(inliers) / 30.0, 1.0)
    else:
        score_align = 0.0

    # 2. Change magnitude bell-shaped score (0-30)
    if change_magnitude < 0.05:
        score_change = 30.0 * (change_magnitude / 0.05)
    elif change_magnitude <= 0.35:
        score_change = 30.0
    elif change_magnitude <= 0.60:
        score_change = 30.0 * (1.0 - (change_magnitude - 0.35) / 0.25)
    else:
        decay = max(0.0, 1.0 - (change_magnitude - 0.60) / 0.20)
        score_change = 5.0 * decay

    # 3. Roughness drop score (0-35)
    if roughness_drop_ratio is not None and roughness_drop_ratio > 0.0:
        clamped_ratio = max(0.0, min(1.0, roughness_drop_ratio / 0.5))
        score_roughness = 35.0 * clamped_ratio
    else:
        score_roughness = 0.0

    total = score_align + score_change + score_roughness
    return max(0.0, min(100.0, round(total, 2)))


def analyze_vision(
    before_bytes: bytes,
    after_bytes: bytes,
) -> tuple[VisionResult, VisionArtifacts]:
    """Analyzes visual alignment, difference heatmap, and surface roughness drop.

    Args:
        before_bytes: Raw bytes of the BEFORE image.
        after_bytes: Raw bytes of the AFTER image.

    Returns:
        A tuple of (VisionResult, VisionArtifacts).

    Raises:
        InvalidImageError: If either image buffer is unreadable or corrupted.
    """
    img_before = _decode_image(before_bytes, "before")
    img_after = _decode_image(after_bytes, "after")

    h_b, w_b = img_before.shape[:2]
    h_a, w_a = img_after.shape[:2]

    flags: list[str] = []

    # 1. Grayscale and CLAHE for illumination invariance
    try:
        gray_b = cv2.cvtColor(img_before, cv2.COLOR_BGR2GRAY)
        gray_a = cv2.cvtColor(img_after, cv2.COLOR_BGR2GRAY)
        clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
        gray_b_clahe = clahe.apply(gray_b)
        gray_a_clahe = clahe.apply(gray_a)
    except Exception as exc:
        logger.warning("CLAHE enhancement failed: %s", exc)
        gray_b_clahe = cv2.cvtColor(img_before, cv2.COLOR_BGR2GRAY)
        gray_a_clahe = cv2.cvtColor(img_after, cv2.COLOR_BGR2GRAY)

    # 2. ORB Feature Extraction
    kp_before: list[cv2.KeyPoint] = []
    kp_after: list[cv2.KeyPoint] = []
    des_before: Optional[np.ndarray] = None
    des_after: Optional[np.ndarray] = None

    try:
        orb = cv2.ORB_create(1500)
        kp_before, des_before = orb.detectAndCompute(gray_b_clahe, None)
        kp_after, des_after = orb.detectAndCompute(gray_a_clahe, None)
    except Exception as exc:
        logger.warning("ORB detectAndCompute failed: %s", exc)

    keypoints_before = len(kp_before)
    keypoints_after = len(kp_after)

    aligned_after: np.ndarray
    validity_mask: np.ndarray
    alignment_succeeded = False
    inliers = 0
    good_matches_count = 0

    has_enough_features = (
        des_before is not None
        and des_after is not None
        and len(des_before) >= 8
        and len(des_after) >= 8
    )

    if not has_enough_features:
        alignment_succeeded = False
        flags.append("INSUFFICIENT_FEATURES")
        try:
            aligned_after = cv2.resize(img_after, (w_b, h_b))
        except Exception:
            aligned_after = np.zeros_like(img_before)
        validity_mask = np.ones((h_b, w_b), dtype=bool)
    else:
        # 3. Feature Matching with Lowe's Ratio Test and Hamming Distance Cap
        try:
            matcher = cv2.BFMatcher(cv2.NORM_HAMMING)
            raw_matches = matcher.knnMatch(des_after, des_before, k=2)
            good_matches = []
            for pair in raw_matches:
                if len(pair) >= 2:
                    m, n = pair[0], pair[1]
                    if m.distance < 0.75 * n.distance and m.distance <= 64:
                        good_matches.append(m)
            good_matches_count = len(good_matches)
        except Exception as exc:
            logger.warning("Descriptor matching failed: %s", exc)
            good_matches = []
            good_matches_count = 0

        # 4. Homography Estimation and Perspective Warping
        H: Optional[np.ndarray] = None
        mask: Optional[np.ndarray] = None

        if good_matches_count >= 8:
            try:
                src_pts = np.float32([kp_after[m.queryIdx].pt for m in good_matches]).reshape(-1, 1, 2)
                dst_pts = np.float32([kp_before[m.trainIdx].pt for m in good_matches]).reshape(-1, 1, 2)
                H, mask = cv2.findHomography(src_pts, dst_pts, cv2.RANSAC, 5.0)
                inliers = int(mask.sum()) if mask is not None else 0
            except (cv2.error, Exception) as exc:
                logger.warning("cv2.findHomography failed: %s", exc)
                H = None
                inliers = 0

        if _is_homography_valid(H, inliers):
            try:
                aligned_after = cv2.warpPerspective(img_after, H, (w_b, h_b))
                mask_after = np.ones((h_a, w_a), dtype=np.uint8) * 255
                warped_mask = cv2.warpPerspective(mask_after, H, (w_b, h_b))
                validity_mask = warped_mask > 200
                alignment_succeeded = True
            except Exception as exc:
                logger.warning("cv2.warpPerspective failed: %s", exc)
                aligned_after = cv2.resize(img_after, (w_b, h_b))
                validity_mask = np.ones((h_b, w_b), dtype=bool)
                alignment_succeeded = False
                flags.append("ALIGNMENT_FAILED: scenes may not match (possible different location)")
        else:
            alignment_succeeded = False
            flags.append("ALIGNMENT_FAILED: scenes may not match (possible different location)")
            try:
                aligned_after = cv2.resize(img_after, (w_b, h_b))
            except Exception:
                aligned_after = np.zeros_like(img_before)
            validity_mask = np.ones((h_b, w_b), dtype=bool)

    # 5. Change Magnitude and JET Heatmap
    try:
        gray_aligned = cv2.cvtColor(aligned_after, cv2.COLOR_BGR2GRAY)
        blur_b = cv2.GaussianBlur(gray_b, (5, 5), 0)
        blur_a = cv2.GaussianBlur(gray_aligned, (5, 5), 0)
        diff = cv2.absdiff(blur_b, blur_a)

        if np.any(validity_mask):
            change_magnitude = float(np.mean(diff[validity_mask]) / 255.0)
        else:
            change_magnitude = 0.0

        diff_heatmap = cv2.applyColorMap(diff, cv2.COLORMAP_JET)
        diff_heatmap[~validity_mask] = 0
    except Exception as exc:
        logger.warning("Difference computation failed: %s", exc)
        change_magnitude = 0.0
        diff = np.zeros((h_b, w_b), dtype=np.uint8)
        diff_heatmap = np.zeros((h_b, w_b, 3), dtype=np.uint8)

    change_magnitude = max(0.0, min(1.0, change_magnitude))

    # 6. Defect ROI Localization (Otsu + Contours)
    defect_roi: Optional[tuple[int, int, int, int]] = None
    try:
        diff_masked = diff.copy()
        diff_masked[~validity_mask] = 0
        _, thresh = cv2.threshold(diff_masked, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)
        kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (5, 5))
        closed = cv2.morphologyEx(thresh, cv2.MORPH_CLOSE, kernel)
        opened = cv2.morphologyEx(closed, cv2.MORPH_OPEN, kernel)
        contours, _ = cv2.findContours(opened, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

        if contours:
            largest = max(contours, key=cv2.contourArea)
            if cv2.contourArea(largest) >= 25.0:
                x, y, w, h = cv2.boundingRect(largest)
                pad_x = int(round(w * 0.10))
                pad_y = int(round(h * 0.10))
                x0 = max(0, x - pad_x)
                y0 = max(0, y - pad_y)
                x1 = min(w_b, x + w + pad_x)
                y1 = min(h_b, y + h + pad_y)
                defect_roi = (x0, y0, max(1, x1 - x0), max(1, y1 - y0))
    except Exception as exc:
        logger.warning("Defect ROI localization failed: %s", exc)

    if defect_roi is None:
        # Central 50% crop fallback
        cw = max(1, w_b // 2)
        ch = max(1, h_b // 2)
        cx = (w_b - cw) // 2
        cy = (h_b - ch) // 2
        defect_roi = (cx, cy, cw, ch)

    # 7. Surface Roughness Analysis via Laplacian Variance
    roughness_before: Optional[float] = None
    roughness_after: Optional[float] = None
    roughness_drop_ratio: Optional[float] = None

    try:
        rx, ry, rw, rh = defect_roi
        roi_b = gray_b[ry : ry + rh, rx : rx + rw]
        roi_a = gray_aligned[ry : ry + rh, rx : rx + rw]

        if roi_b.size > 0 and roi_a.size > 0:
            lap_b = cv2.Laplacian(roi_b, cv2.CV_64F)
            lap_a = cv2.Laplacian(roi_a, cv2.CV_64F)
            roughness_before = float(lap_b.var())
            roughness_after = float(lap_a.var())
            roughness_drop_ratio = (roughness_before - roughness_after) / max(
                roughness_before, 1e-6
            )

            if roughness_drop_ratio < 0.0:
                flags.append("SURFACE_ROUGHER_AFTER")
            elif roughness_drop_ratio < 0.15 and alignment_succeeded:
                flags.append("NO_SURFACE_SMOOTHING")
    except Exception as exc:
        logger.warning("Surface roughness calculation failed: %s", exc)

    # 8. Score Calculation
    score = _compute_vision_score(
        alignment_succeeded=alignment_succeeded,
        inliers=inliers,
        change_magnitude=change_magnitude,
        roughness_drop_ratio=roughness_drop_ratio,
    )

    result = VisionResult(
        keypoints_before=keypoints_before,
        keypoints_after=keypoints_after,
        good_matches=good_matches_count,
        inliers=inliers,
        alignment_succeeded=alignment_succeeded,
        change_magnitude=round(change_magnitude, 4),
        roughness_before=round(roughness_before, 2) if roughness_before is not None else None,
        roughness_after=round(roughness_after, 2) if roughness_after is not None else None,
        roughness_drop_ratio=round(roughness_drop_ratio, 4) if roughness_drop_ratio is not None else None,
        flags=flags,
        score=score,
    )

    artifacts = VisionArtifacts(
        aligned_after=aligned_after,
        diff_heatmap=diff_heatmap,
        defect_roi=defect_roi,
    )

    return result, artifacts
